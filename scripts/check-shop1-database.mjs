// Isolated PostgreSQL (PGlite). Never opens a connection to TEST or PROD.
// npm install --prefix tmp/shop1-db-check --ignore-scripts @electric-sql/pglite@0.3.14
import { PGlite } from '../tmp/shop1-db-check/node_modules/@electric-sql/pglite/dist/index.js';
import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8').replace(/^\uFEFF/, '');
const prod = JSON.parse(read('docs/shop1-db-evidence/prod-preflight-2026-09-09.json'))[0].shop1_preflight;
const test = JSON.parse(read('docs/shop1-db-evidence/test-preflight-2026-09-09.json'))[0].shop1_preflight;
const migration = read('supabase/shop1-review/001_inventory_v2_candidate.sql');
const names = ['inventory', 'tasks', 'material_requests', 'work_cards', 'work_card_history'];
const q = value => `"${value.replaceAll('"', '""')}"`;
let checks = 0;

async function run(schema, withReconcile, label) {
  const db = new PGlite();
  try {
    await db.exec('CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;');
    // Recreate observed columns, NULL rules and defaults. Foreign keys to unrelated
    // production modules and RLS/auth helpers are intentionally outside this fixture.
    for (const name of names) {
      const columns = schema.columns.filter(c => c.table_name === name).map(c => {
        let def = `${q(c.column_name)} ${c.data_type}`;
        if (c.column_name === 'id') def += c.data_type === 'uuid' ? ' PRIMARY KEY DEFAULT gen_random_uuid()' : ' GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY';
        else {
          if (c.column_default != null) def += ` DEFAULT ${c.column_default}`;
          if (c.is_nullable === 'NO') def += ' NOT NULL';
        }
        return def;
      });
      await db.exec(`CREATE TABLE public.${q(name)} (${columns.join(',')});`);
    }
    if (withReconcile) {
      const trigger = prod.triggers.find(t => t.trigger_name === 'trg_reconcile_inventory_reserve');
      await db.exec(trigger.function_definition);
      await db.exec(trigger.definition);
    }
    await db.exec(migration);
    await db.exec(read('supabase/shop1-review/002_test_smoke_rollback.sql'));
    assert.equal((await db.query('SELECT count(*)::int n FROM shop1_v2.tasks')).rows[0].n,0); checks++;
    assert.equal((await db.query('SELECT accept_new_tasks FROM shop1_v2.settings')).rows[0].accept_new_tasks,false); checks++;
    const sql = (s, args=[]) => db.query(s, args);
    const scalar = async (s,args=[]) => (await sql(s,args)).rows[0];
    const fails = async (s,args,pattern) => { await assert.rejects(sql(s,args),pattern); checks++; };
    const complete = (card, actual={}) => sql('SELECT public.shop1_v2_complete_cutting($1,$2,$3,$4) result',[card,JSON.stringify(actual),'Оператор','Зміна 1']);
    const makeTask = async ({sheets=15, other=0, cutters=0}={}) => {
      const task = (await scalar("INSERT INTO tasks(step,warehouse_conf,engineer_conf,director_conf) VALUES('Розкрій','true',true,true) RETURNING id")).id;
      const stock = (await scalar("INSERT INTO inventory(name,unit,total_qty,reserved_qty,warehouse) VALUES('Лист','л',30,$1,'operational') RETURNING id",[withReconcile?0:sheets+other])).id;
      const req = (await scalar("INSERT INTO material_requests(task_id,inventory_id,quantity,status,category) VALUES($1,$2,$3,'issued','sheet') RETURNING id",[task,stock,sheets])).id;
      if(other) await sql("INSERT INTO material_requests(inventory_id,quantity,status,category) VALUES($1,$2,'issued','sheet')",[stock,other]);
      let cutterReq, cutterStock;
      if(cutters) {
        cutterStock=(await scalar("INSERT INTO inventory(name,unit,nomenclature_id,total_qty,reserved_qty,warehouse) VALUES('Фреза','шт',$1,10,$2,'operational') RETURNING id",[randomUUID(),withReconcile?0:cutters])).id;
        cutterReq=(await scalar("INSERT INTO material_requests(task_id,inventory_id,quantity,status) VALUES($1,$2,$3,'issued') RETURNING id",[task,cutterStock,cutters])).id;
      }
      return {task,stock,req,cutterReq,cutterStock};
    };
    const enroll = f => sql('SELECT public.shop1_v2_enroll($1)',[f.task]);
    const payload = (f,sheets=3,cutters=0) => [{quantity:sheets*2,nomenclature_id:randomUUID(),machine:'Тест',allocations:[{request_id:f.req,kind:'sheet',planned_qty:sheets},...(cutters?[{request_id:f.cutterReq,kind:'cutter',planned_qty:cutters}]:[])]}];
    const create = async (f,p=payload(f),key=randomUUID()) => (await scalar('SELECT public.shop1_v2_create_cards($1,$2,$3) ids',[f.task,key,JSON.stringify(p)])).ids;
    const start = card => sql("UPDATE work_cards SET status='in-progress',started_at=now() WHERE id=$1",[card]);
    const balances = f => scalar('SELECT total_qty::int total,reserved_qty::int reserved FROM inventory WHERE id=$1',[f.stock]);
    const f=await makeTask({other:4});
    await fails('SELECT public.shop1_v2_enroll($1)',[f.task],/disabled/);
    await db.exec('UPDATE shop1_v2.settings SET accept_new_tasks=true,completion_enabled=true;');
    for (const missing of ["warehouse_conf='partial'","engineer_conf=false","director_conf=false"]) {
      await sql(`UPDATE tasks SET ${missing} WHERE id=$1`,[f.task]);
      await fails('SELECT public.shop1_v2_enroll($1)',[f.task],/Three full approvals/);
      await sql("UPDATE tasks SET warehouse_conf='true',engineer_conf=true,director_conf=true WHERE id=$1",[f.task]);
    }
    await enroll(f); await enroll(f);
    assert.deepEqual(await balances(f),{total:30,reserved:19}); checks++;
    await fails("INSERT INTO material_requests(task_id,inventory_id,quantity,status,category) VALUES($1,$2,1,'pending','sheet')",[f.task,f.stock],/cannot reserve sheets again/);
    const p=payload(f); const key=randomUUID(); const [card]=await create(f,p,key);
    assert.deepEqual(await create(f,p,key),[card]); checks++;
    await fails('SELECT public.shop1_v2_create_cards($1,$2,$3)',[f.task,key,JSON.stringify(payload(f))],/different payload/);
    await fails('SELECT public.shop1_v2_create_cards($1,$2,$3)',[f.task,randomUUID(),JSON.stringify(payload(f,13))],/exceeds original/);
    await sql("UPDATE tasks SET director_conf=false WHERE id=$1",[f.task]);
    await fails('SELECT public.shop1_v2_create_cards($1,$2,$3)',[f.task,randomUUID(),JSON.stringify(payload(f))],/Three full approvals/);
    await sql("UPDATE tasks SET director_conf=true WHERE id=$1",[f.task]);
    await start(card); assert.deepEqual(await balances(f),{total:30,reserved:19}); checks++;
    await fails("UPDATE work_cards SET status='at-buffer' WHERE id=$1",[card],/requires V2 writer/);
    await fails('UPDATE material_requests SET quantity=0 WHERE id=$1',[f.req],/requires V2 writer/);
    await complete(card); assert.deepEqual(await balances(f),{total:27,reserved:16}); checks++;
    await complete(card); assert.deepEqual(await balances(f),{total:27,reserved:16}); checks++;
    await assert.rejects(complete(card,{[randomUUID()]:1}),/different facts/); checks++;
    await fails("UPDATE work_cards SET status='in-progress' WHERE id=$1",[card],/cannot restart/);
    await sql("UPDATE work_cards SET operation='Галтовка',status='in-progress' WHERE id=$1",[card]);
    await complete(card); assert.deepEqual(await balances(f),{total:27,reserved:16}); checks++;
    const [next]=await create(f,payload(f,12)); await start(next); await complete(next);
    assert.deepEqual(await balances(f),{total:15,reserved:4}); checks++;
    const c=await makeTask({cutters:2}); await enroll(c); const [cc]=await create(c,payload(c,3,2)); await start(cc);
    await assert.rejects(complete(cc,{}),/explicit sufficient allocation/); checks++;
    await assert.rejects(complete(cc,{[c.cutterReq]:3}),/explicit sufficient allocation/); checks++;
    await assert.rejects(complete(cc,{[c.cutterReq]:-1}),/explicit sufficient allocation/); checks++;
    await assert.rejects(complete(cc,{[c.cutterReq]:1}),/restoration dependency missing/); checks++;
    assert.deepEqual(await balances(c),{total:30,reserved:15}); checks++;
    assert.equal((await scalar('SELECT status FROM work_cards WHERE id=$1',[cc])).status,'in-progress'); checks++;
    // Run the actual exported PROD restoration function. Only its classifier is
    // substituted: this fixture treats every cutter as a faceting cutter.
    for(const name of ['cutter_usage_events','cutter_restoration_batches']) {
      const columns=prod.columns.filter(c=>c.table_name===name).map(c=>`${q(c.column_name)} ${c.data_type}${c.column_default!=null?` DEFAULT ${c.column_default}`:''}${c.is_nullable==='NO'?' NOT NULL':''}`);
      await db.exec(`CREATE TABLE public.${q(name)} (${columns.join(',')});`);
    }
    await db.exec(`CREATE TABLE public.nomenclatures(id uuid PRIMARY KEY,name text,type text);
      CREATE TABLE public.cutter_restoration_events(batch_id uuid,event_type text,actor_id bigint,actor_name text,metadata jsonb);
      CREATE FUNCTION public.is_faceting_cutter(uuid) RETURNS boolean LANGUAGE sql AS $$ SELECT true $$;`);
    await sql("INSERT INTO nomenclatures SELECT nomenclature_id,name,'consumable' FROM inventory WHERE id=$1",[c.cutterStock]);
    await db.exec(prod.functions.find(f=>f.proname==='register_cutter_usage').definition);
    await complete(cc,{[c.cutterReq]:1}); await complete(cc,{[c.cutterReq]:1});
    assert.deepEqual(await scalar('SELECT total_qty::int total,reserved_qty::int reserved FROM inventory WHERE id=$1',[c.cutterStock]),{total:9,reserved:0}); checks++;
    assert.equal((await scalar('SELECT count(*)::int n FROM cutter_usage_events')).n,1); checks++;
    assert.equal((await scalar('SELECT count(*)::int n FROM cutter_restoration_batches')).n,1); checks++;
    const z=await makeTask({cutters:2}); await enroll(z); const [zc]=await create(z,payload(z,3,2)); await start(zc); await complete(zc,{[z.cutterReq]:0});
    assert.deepEqual(await scalar('SELECT total_qty::int total,reserved_qty::int reserved FROM inventory WHERE id=$1',[z.cutterStock]),{total:10,reserved:0}); checks++;
    const fault=await makeTask(); await enroll(fault); const [fc]=await create(fault); await start(fc);
    await db.exec(`CREATE FUNCTION public.test_fail_history() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'injected history failure'; END; $$;
      CREATE TRIGGER test_fail_history BEFORE INSERT ON work_card_history FOR EACH ROW EXECUTE FUNCTION test_fail_history();`);
    await assert.rejects(complete(fc),/injected history failure/); checks++;
    assert.deepEqual(await balances(fault),{total:30,reserved:15}); checks++;
    assert.equal((await scalar('SELECT count(*)::int n FROM shop1_v2.completions WHERE card_id=$1',[fc])).n,0); checks++;
    await db.exec('DROP TRIGGER test_fail_history ON work_card_history;');
    await complete(fc);
    // Failure after restoration has written must roll back usage/batches too.
    const restoreFault=await makeTask({cutters:2}); await enroll(restoreFault);
    await sql("INSERT INTO nomenclatures SELECT nomenclature_id,name,'consumable' FROM inventory WHERE id=$1",[restoreFault.cutterStock]);
    const [rfc]=await create(restoreFault,payload(restoreFault,3,2)); await start(rfc);
    await db.exec('CREATE TRIGGER test_fail_history BEFORE INSERT ON work_card_history FOR EACH ROW EXECUTE FUNCTION test_fail_history();');
    await assert.rejects(complete(rfc,{[restoreFault.cutterReq]:1}),/injected history failure/); checks++;
    assert.equal((await scalar('SELECT count(*)::int n FROM cutter_usage_events WHERE source_card_id=$1',[rfc])).n,0); checks++;
    assert.equal((await scalar('SELECT count(*)::int n FROM cutter_restoration_batches WHERE source_card_id=$1',[rfc])).n,0); checks++;
    assert.deepEqual(await balances(restoreFault),{total:30,reserved:15}); checks++;
    await db.exec('DROP TRIGGER test_fail_history ON work_card_history;');
    // Partial scrap and a different responsible operator: sheet quantity is
    // unchanged, good pieces and scrap movement are committed together.
    const scrap=await makeTask(); await enroll(scrap); const sp=payload(scrap); const [sc]=await create(scrap,sp); await start(sc);
    const scrapStock=(await scalar("INSERT INTO inventory(name,unit,nomenclature_id,type,warehouse,total_qty,reserved_qty) VALUES('Брак','шт',$1,'scrap_ready','operational',0,0) RETURNING id",[sp[0].nomenclature_id])).id;
    const scrapArgs=[sc,'{}','Оператор','Зміна 1',2,scrapStock,'Інший оператор'];
    await sql('SELECT public.shop1_v2_complete_cutting($1,$2,$3,$4,$5,$6,$7)',scrapArgs);
    await sql('SELECT public.shop1_v2_complete_cutting($1,$2,$3,$4,$5,$6,$7)',scrapArgs);
    assert.deepEqual(await balances(scrap),{total:27,reserved:12}); checks++;
    assert.equal((await scalar('SELECT total_qty::int n FROM inventory WHERE id=$1',[scrapStock])).n,2); checks++;
    assert.equal((await scalar('SELECT quantity FROM work_cards WHERE id=$1',[sc])).quantity,4); checks++;
    assert.equal((await scalar('SELECT count(*)::int n FROM work_card_history WHERE card_id=$1',[sc])).n,2); checks++;
    const full=await makeTask(); await enroll(full); const fp=payload(full); const [fullCard]=await create(full,fp); await start(fullCard);
    const fullStock=(await scalar("INSERT INTO inventory(name,unit,nomenclature_id,type,warehouse,total_qty,reserved_qty) VALUES('Повний брак','шт',$1,'scrap_ready','operational',0,0) RETURNING id",[fp[0].nomenclature_id])).id;
    await fails('SELECT public.shop1_v2_complete_cutting($1,$2,$3,$4,$5,$6,$7)',[fullCard,'{}','Оператор','Зміна 1',7,fullStock,null],/Invalid scrap/);
    await fails('SELECT public.shop1_v2_complete_cutting($1,$2,$3,$4,$5,$6,$7)',[fullCard,'{}','Оператор','Зміна 1',2,scrapStock,null],/identity mismatch/);
    await sql('SELECT public.shop1_v2_complete_cutting($1,$2,$3,$4,$5,$6,$7)',[fullCard,'{}','Оператор','Зміна 1',6,fullStock,null]);
    assert.equal((await scalar('SELECT quantity FROM work_cards WHERE id=$1',[fullCard])).quantity,0); checks++;
    assert.deepEqual(await balances(full),{total:27,reserved:12}); checks++;
    // First reservation happens before engineer/director approve, once per task.
    const pending=await makeTask();
    await sql("UPDATE material_requests SET status='pending' WHERE id=$1",[pending.req]);
    if(!withReconcile) await sql('UPDATE inventory SET reserved_qty=0 WHERE id=$1',[pending.stock]);
    await sql("UPDATE tasks SET warehouse_conf='false',engineer_conf=false,director_conf=false WHERE id=$1",[pending.task]);
    await sql('SELECT public.shop1_v2_reserve_sheets($1)',[pending.task]);
    await sql('SELECT public.shop1_v2_reserve_sheets($1)',[pending.task]);
    assert.deepEqual(await balances(pending),{total:30,reserved:15}); checks++;
    await fails('SELECT public.shop1_v2_create_cards($1,$2,$3)',[pending.task,randomUUID(),JSON.stringify(payload(pending))],/Three full approvals/);
    const short=await makeTask({sheets:31});
    await sql("UPDATE material_requests SET status='pending' WHERE id=$1",[short.req]);
    if(!withReconcile) await sql('UPDATE inventory SET reserved_qty=0 WHERE id=$1',[short.stock]);
    await fails('SELECT public.shop1_v2_reserve_sheets($1)',[short.task],/Insufficient operational/);
    assert.equal((await scalar('SELECT count(*)::int n FROM shop1_v2.tasks WHERE task_id=$1',[short.task])).n,0); checks++;
    assert.deepEqual(await balances(short),{total:30,reserved:0}); checks++;
    // Two explicit materials on one task must retain separate remaining reserves.
    const multi=await makeTask();
    const secondStock=(await scalar("INSERT INTO inventory(name,unit,total_qty,reserved_qty,warehouse) VALUES('T700','л',20,$1,'operational') RETURNING id",[withReconcile?0:8])).id;
    const secondReq=(await scalar("INSERT INTO material_requests(task_id,inventory_id,quantity,status,category) VALUES($1,$2,8,'issued','sheet') RETURNING id",[multi.task,secondStock])).id;
    await enroll(multi); const mp=payload({...multi,req:secondReq},4); const [mc]=await create(multi,mp); await start(mc); await complete(mc);
    assert.deepEqual(await balances(multi),{total:30,reserved:15}); checks++;
    assert.deepEqual(await scalar('SELECT total_qty::int total,reserved_qty::int reserved FROM inventory WHERE id=$1',[secondStock]),{total:16,reserved:4}); checks++;
    const foreign=await makeTask(); await enroll(foreign);
    await fails('SELECT public.shop1_v2_create_cards($1,$2,$3)',[foreign.task,randomUUID(),JSON.stringify(payload({...foreign,req:multi.req}))],/issued to this task/);
    const inconsistent=await makeTask(); await enroll(inconsistent);
    await sql('UPDATE inventory SET reserved_qty=0 WHERE id=$1',[inconsistent.stock]);
    await fails('SELECT public.shop1_v2_create_cards($1,$2,$3)',[inconsistent.task,randomUUID(),JSON.stringify(payload(inconsistent))],/Inconsistent inventory/);
    await db.exec('GRANT SELECT,INSERT,UPDATE,DELETE ON public.work_cards,public.material_requests TO anon; SET ROLE anon;');
    // Invoker table traffic still works for ordinary cards; private membership
    // checks in SECURITY DEFINER guards must not break the existing application.
    const legacy=(await scalar("INSERT INTO work_cards(operation,status,quantity) VALUES('Розкрій','new',1) RETURNING id")).id;
    await sql("UPDATE work_cards SET status='in-progress' WHERE id=$1",[legacy]); checks++;
    await fails("UPDATE work_cards SET quantity=1 WHERE id=$1",[rfc],/requires V2 writer/);
    await fails("INSERT INTO work_cards(task_id,operation,status,quantity) VALUES($1,'Розкрій','new',1)",[multi.task],/requires V2 card generation/);
    await fails('SELECT public.shop1_v2_enroll($1)',[f.task],/permission denied/);
    await db.exec('RESET ROLE;');
    await db.exec('UPDATE shop1_v2.settings SET accept_new_tasks=false,completion_enabled=false;');
    await complete(card); checks++; // A committed retry remains readable while paused.
    await assert.rejects(complete(rfc,{[restoreFault.cutterReq]:1}),/disabled/); checks++;
    assert.equal((await scalar("SELECT has_function_privilege('authenticated','public.shop1_v2_complete_cutting(uuid,jsonb,text,text,integer,uuid,text)','EXECUTE') allowed")).allowed,false); checks++;
    console.log(`PASS ${label}`);
  } finally { await db.close(); }
}
await run(prod,true,'PROD columns + actual reserve trigger');
await run(test,false,'TEST columns without reserve trigger');
console.log(`PASS ${checks} database assertions; no remote connections. Multi-session concurrency, classifier and production auth are not covered.`);
