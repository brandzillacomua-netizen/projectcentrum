-- 1. system_users: зміна id на bigint (бо історично в системі id користувачів — це числа 13, 88 тощо)
DROP TABLE IF EXISTS public.system_users CASCADE;
CREATE TABLE public.system_users (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  login text UNIQUE NOT NULL,
  password text,
  first_name text,
  last_name text,
  position text,
  department text,
  shift text,
  access_rights jsonb DEFAULT '{}'::jsonb,
  notification_settings jsonb DEFAULT '{}'::jsonb,
  avatar text,
  last_seen text,
  shift_calendar jsonb DEFAULT '[]'::jsonb,
  created_at timestamptz DEFAULT now()
);
ALTER TABLE public.system_users ENABLE ROW LEVEL SECURITY;
CREATE POLICY "staging_all_access_system_users" ON public.system_users FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

