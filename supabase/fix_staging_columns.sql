-- 6. RPC verify_user_password (fallback перевірка логіну без Supabase Auth)
CREATE OR REPLACE FUNCTION public.verify_user_password(login_input text, password_input text)
RETURNS jsonb AS $$
DECLARE
  v_user record;
BEGIN
  SELECT * INTO v_user FROM public.system_users WHERE lower(login) = lower(login_input) LIMIT 1;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'error', 'Користувача не знайдено');
  END IF;
  IF v_user.password IS NOT NULL AND v_user.password = password_input THEN
    RETURN jsonb_build_object('success', true, 'user', row_to_json(v_user));
  ELSE
    RETURN jsonb_build_object('success', false, 'error', 'Невірний пароль');
  END IF;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;
