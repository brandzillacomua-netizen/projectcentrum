function parseParts() {
  const lines = rawInput.split('\n').map(l => l.trim()).filter(Boolean);
  const items = [];

  let currentItem = null;

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    if (line.startsWith('Мат:')) {
      if (currentItem) {
        currentItem.rawSheet = line.replace('Мат:', '').trim();
      }
    } else if (line.startsWith('Норма:')) {
      if (currentItem) {
        const normMatch = line.match(/(\d+)\s*шт\/л/);
        currentItem.unitsPerSheet = normMatch ? parseInt(normMatch[1]) : 1;
      }
    } else if (line.startsWith('—') || line.startsWith('Час:')) {
      // separator lines
      continue;
    } else {
      // This is a part name line!
      if (!line.includes('от бачиш')) {
        currentItem = {
          name: line,
          rawSheet: '',
          unitsPerSheet: 1
        };
        items.push(currentItem);
      }
    }
  }

  // Exclude hardware / screws if any accidentally slipped in (like М3x12, Гвинт М3x16)
  const filtered = items.filter(it => !it.name.startsWith('М3x') && !it.name.startsWith('Гвинт М3'));
  return filtered;
}

