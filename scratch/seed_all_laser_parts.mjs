async function seedLaserParts() {
  console.log('Deleting existing items in cat_parts...');
  await supabase.from('nomenclatures_v2').delete().eq('group_id', 'cat_parts');

  let codeCounter = 90701;
  const records = parsedParts.map(item => ({
    code: 'V2-' + (codeCounter++),
    name: item.name,
    group_id: 'cat_parts',
    unit: 'шт',
    rule_type: 'frame_part',
    rule_params: {
      customName: item.name,
      rawSheet: item.rawSheet || 'Лист Т300 (3мм)',
      unitsPerSheet: item.unitsPerSheet || 1
    },
    status: 'active'
  }));

  console.log(`Inserting ${records.length} laser parts into nomenclatures_v2...`);
  
  for (let i = 0; i < records.length; i += 50) {
    const chunk = records.slice(i, i + 50);
    const { error } = await supabase.from('nomenclatures_v2').upsert(chunk, { onConflict: 'code' });
    if (error) console.error('Error inserting chunk:', error.message);
  }

  console.log('✅ Successfully seeded all laser parts with material & units_per_sheet into nomenclatures_v2!');

  const { data } = await supabase.from('nomenclatures_v2').select('*').eq('group_id', 'cat_parts');
  console.log(`Total count in 03. Деталі: ${data ? data.length : 0}`);
}

